// Forked from the company's Pattern Library (Eleventy 3 + Nunjucks). Owned by the init-proyecto skill since 12.1.0.
// Bundles the styles and scripts that live inside each component into the two files the library
// ships: assets/css/library.css and assets/js/library.js (DEC-021).
//
// Styles and scripts are separate and independent:
//   <pattern>/<pattern>.css   the component's styles. Collected automatically.
//   <pattern>/<pattern>.js    the component's behaviour. Exists only when the component needs a script.
// Both are collected in cascade order: `_base` first (tokens, reset), then every level in the order of
// LEVELS, then the pattern folders alphabetically. The output is minified unless MINIFY=0.
import fs from "node:fs";
import path from "node:path";
import { build, formatMessages } from "esbuild";
import { LEVELS } from "./library-config.js";

const PATTERNS = path.resolve("src/patterns");
const BANNER = "/* Generated by lib/assets.js from the component files under src/patterns/. Do not edit. */";

const isPattern = (dir) => fs.existsSync(path.join(dir, `${path.basename(dir)}.njk`));
const posix = (file) => file.split(path.sep).join("/");

// Every stylesheet and script of the library, in cascade order.
export function collectAssets() {
  const css = [];
  const js = [];

  for (const [list, file] of [
    [css, "base.css"],
    [js, "base.js"],
  ]) {
    const base = path.join(PATTERNS, "_base", file);
    if (fs.existsSync(base)) list.push(base);
  }

  const walk = (dir) => {
    for (const name of fs.readdirSync(dir).sort()) {
      if (name.startsWith(".") || name.startsWith("_")) continue;
      const full = path.join(dir, name);
      if (!fs.statSync(full).isDirectory()) continue;
      if (isPattern(full)) {
        for (const [list, ext] of [
          [css, "css"],
          [js, "js"],
        ]) {
          const file = path.join(full, `${name}.${ext}`);
          if (fs.existsSync(file)) list.push(file);
        }
        continue;
      }
      walk(full);
    }
  };
  for (const level of LEVELS) {
    const dir = path.join(PATTERNS, level.key);
    if (fs.existsSync(dir)) walk(dir);
  }
  return { css, js };
}

// Scripts must not pull styles in: styles are collected on their own from `<name>.css`.
const noCssInScripts = {
  name: "no-css-in-scripts",
  setup(b) {
    b.onResolve({ filter: /\.css$/ }, (args) => ({
      errors: [
        {
          text: `Scripts must not import CSS (${args.path}): styles are collected automatically from each component's <name>.css (DEC-021)`,
        },
      ],
    }));
  },
};

const kb = (n) => (n / 1024).toFixed(1) + " kB";

// The design system's CSS references its icons and fonts as ../assets/… (relative to design-system/css/).
// esbuild must not try to bundle those files: they stay as URLs and are rewritten below to /assets/ds/…,
// where eleventy.config.js serves design-system/assets/.
const DS_ASSET_EXTERNALS = ["*.png", "*.svg", "*.jpg", "*.jpeg", "*.gif", "*.webp", "*.avif", "*.woff", "*.woff2", "*.ttf", "*.otf"];
const rewriteDsUrls = (css) => css.replace(/url\((['"]?)(?:\.\.\/)+(?:design-system\/)?assets\//g, "url($1/assets/ds/");

const common = (minify) => ({
  absWorkingDir: process.cwd(),
  bundle: true,
  external: DS_ASSET_EXTERNALS,
  minify,
  target: "es2018",
  write: false,
  logLevel: "silent",
  legalComments: "none",
  banner: { js: BANNER, css: BANNER },
});

// Compiles the two bundles into `<outputDir>/assets/{css,js}/library.*`.
// strict: throw on a compile error (build). Otherwise log it and leave the previous files (serve).
export async function buildAssets({ outputDir, strict = true, minify = process.env.MINIFY !== "0" }) {
  const { css, js } = collectAssets();
  try {
    const [cssResult, jsResult] = await Promise.all([
      build({
        ...common(minify),
        stdin: {
          contents: css.map((f) => `@import ${JSON.stringify(posix(f))};`).join("\n"),
          resolveDir: process.cwd(),
          sourcefile: "library-entry.css",
          loader: "css",
        },
        outfile: "library.css",
      }),
      build({
        ...common(minify),
        stdin: {
          contents: js.map((f) => `import ${JSON.stringify(posix(f))};`).join("\n"),
          resolveDir: process.cwd(),
          sourcefile: "library-entry.js",
          loader: "js",
        },
        format: "iife",
        outfile: "library.js",
        plugins: [noCssInScripts],
      }),
    ]);

    const out = { css: rewriteDsUrls(cssResult.outputFiles[0].text), js: jsResult.outputFiles[0].text };
    for (const [ext, text] of Object.entries(out)) {
      const target = path.join(outputDir, "assets", ext, `library.${ext}`);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, text);
    }
    console.log(
      `[assets] library.css ${kb(Buffer.byteLength(out.css))}, library.js ${kb(Buffer.byteLength(out.js))}` +
        `${minify ? " (minified)" : ""} from ${css.length} stylesheet${css.length === 1 ? "" : "s"} and ${js.length} script${js.length === 1 ? "" : "s"}`,
    );
  } catch (err) {
    if (!err.errors) throw err;
    const text = (await formatMessages(err.errors, { kind: "error", color: false })).join("\n");
    if (strict) throw new Error(`Asset build failed:\n${text}`, { cause: err });
    console.error(`[assets] Build failed, keeping the previous files:\n${text}`);
  }
}
